def test_the_counts_add_up(receipt):
    counts = receipt["counts"]
    verdicts = [row["verdict"] for row in receipt["per_observation"]]
    assert counts["observations"] == len(verdicts)
    assert counts["emitted"] == verdicts.count("EMITTED")
    assert counts["refused"] == verdicts.count("REFUSED")
    assert counts["decided_by_the_checker"] == counts["emitted"] + counts["refused"]
    if counts["decided_by_the_checker"]:
        expected = round(counts["refused"] / counts["decided_by_the_checker"], 4)
        assert counts["refusal_rate"] == expected


def test_every_verdict_is_what_the_checker_says_today(receipt, fixture, packets):
    """The receipt is a claim about the checker's output, so run the checker."""
    frozen = {int(d["obs_id"]): d for d in fixture["drafts"]}
    checked = 0
    for row in receipt["per_observation"]:
        if row["verdict"] not in {"EMITTED", "REFUSED"}:
            continue
        draft = frozen[int(row["obs_id"])]["draft"]
        result = verify_note(draft, packets[int(row["obs_id"])])
        expected = "EMITTED" if result.ok else "REFUSED"
        assert row["verdict"] == expected, f"observation {row['obs_id']}"
        assert row.get("codes", []) == result.codes, f"observation {row['obs_id']}"
        checked += 1
    assert checked >= 10, f"only {checked} rows re-checked, so this proves little"


def test_the_checker_sensitivity_is_reproducible(receipt, packets):
    """Recomputed over every observation, and both halves have to survive.

    The receipt's headline used to be a refusal count over one observation. It is now the
    count of drafts refused for the reason they were built to trip, over all of them, so
    this recomputes exactly that: a checker that refused everything for a single reason
    would leave detection_rate below refusal_rate_over_adversarial and this would catch it.
    """
    sens = receipt["checker_sensitivity"]
    assert sens["observations_measured"] == len(packets)

    expected_fired = 0
    refused_at_all = 0
    adversarial = 0
    for packet in packets.values():
        for draft, expected in adversarial_drafts(packet):
            adversarial += 1
            result = verify_note(draft, packet)
            if result.ok:
                continue
            refused_at_all += 1
            if expected in result.codes:
                expected_fired += 1

    controls = 0
    refused_controls = 0
    for packet in packets.values():
        for draft in control_drafts(packet):
            controls += 1
            if not verify_note(draft, packet).ok:
                refused_controls += 1

    assert sens["adversarial_checks"] == adversarial
    assert sens["refused_for_any_reason"] == refused_at_all
    assert sens["caught_for_the_expected_reason"] == expected_fired
    assert sens["control_checks"] == controls
    assert sens["control_refused"] == refused_controls

    # A check is one draft against one packet, so the totals have to factorise. Without
    # this, "525" reads as the size of the adversarial suite, which is 21.
    assert sens["adversarial_checks"] == (
        sens["adversarial_drafts_per_observation"] * sens["observations_measured"]
    )
    assert sens["control_checks"] == (
        sens["control_drafts_per_observation"] * sens["observations_measured"]
    )
    assert sens["adversarial_drafts_per_observation"] == len(adversarial_drafts(packet))
    assert sens["control_drafts_per_observation"] == len(control_drafts(packet))
    assert sens["detection_rate"] == round(expected_fired / adversarial, 4)
    assert sens["refusal_rate_over_adversarial"] == round(refused_at_all / adversarial, 4)
    assert sens["false_refusal_rate"] == round(refused_controls / controls, 4)

    # Both directions have to be reported over a non-empty set. A receipt claiming a
    # perfect detection rate with no control set is the failure this pairing prevents.
    assert controls > 0
    assert adversarial > 0
    assert sens["detection_rate"] <= sens["refusal_rate_over_adversarial"], (
        "detection cannot exceed refusal: every draft caught for the right reason was "
        "refused, so the looser number is an upper bound on the stricter one"
    )


def test_the_stability_block_reports_what_it_measured(receipt):
    """A rate whose denominator is not the thing it says would be worse than no rate."""
    stability = receipt["run_to_run_stability"]
    across = stability["across_processes"]
    if not across.get("passes"):
        pytest.skip("no cross-process pass has been recorded yet")

    compared = sum(p["drafts_compared"] for p in across["passes"])
    differed = sum(p["drafts_that_differed"] for p in across["passes"])
    flips = sum(p["verdict_flips"] for p in across["passes"])
    assert across["drafts_compared"] == compared
    assert across["drafts_that_differed"] == differed
    assert across["verdict_flips"] == flips
    assert across["text_disagreement_rate"] == round(differed / compared, 4)
    assert across["verdict_flip_rate"] == round(flips / compared, 4)
    for record in across["passes"]:
        assert record["verdict_flips"] <= record["drafts_that_differed"], (
            "a verdict cannot flip in a draft that did not change"
        )


def test_the_frequency_finding_is_recomputable(receipt, packets):
    """The headline finding, re-derived from the rows rather than read from the summary.

    Two conditions, and both are re-applied here: within five percent of the observation's
    own receiver frequency in megahertz, and written in megahertz. The unit is read off the
    violation record. An earlier version of both the finding and this check used the numeric
    window alone, which counted any invented number that happened to land in the same range.
    """
    finding = receipt["hallucinated_downlink_frequency"]
    hits = 0
    in_range_wrong_unit = 0
    for row in receipt["per_observation"]:
        packet = packets.get(int(row["obs_id"]))
        if packet is None:
            continue
        true_mhz = packet.exact["receiver_frequency_hz"] / 1e6
        if not true_mhz:
            continue
        for violation in row.get("violations", []):
            if violation["code"] != "UNGROUNDED_NUMBER":
                continue
            assert "literal" in violation and "unit" in violation, (
                "an ungrounded-number violation has to carry its literal and unit "
                "structurally, or a consumer has to parse them back out of a message"
            )
            try:
                value = float(str(violation["literal"]).replace(",", ""))
            except ValueError:
                continue
            if abs(value - true_mhz) / true_mhz > 0.05:
                continue
            if violation["unit"] == "mhz":
                hits += 1
            else:
                in_range_wrong_unit += 1
    assert finding["occurrences"] == hits
    assert finding["in_range_but_not_written_as_a_frequency"] == in_range_wrong_unit
    assert finding["of_observations"] == len(receipt["per_observation"])


