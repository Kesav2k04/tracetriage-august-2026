def test_the_frozen_prompt_contract_is_the_current_one(fixture):
    """A prompt edit without a re-freeze publishes answers to a different question."""
    assert fixture["generation"]["prompt_contract_sha256"] == prompt_contract_sha256(), (
        "the instruction text has changed since these drafts were frozen. Re-run "
        "scripts/run_explanations.py --freeze."
    )


def test_every_frozen_draft_matches_its_own_digest(fixture):
    for draft in fixture["drafts"]:
        actual = hashlib.sha256(draft["draft"].encode("utf-8")).hexdigest()
        assert actual == draft["draft_sha256"], f"observation {draft['obs_id']}"


def test_every_frozen_draft_still_matches_the_packet_it_was_written_from(
    fixture, packets
):
    """The case that would otherwise publish a sentence about superseded facts.

    The console data is regenerated by a different script. If a card's fields change, a
    frozen note is prose about numbers that are no longer on the page, and no type or
    schema can see it.
    """
    stale = []
    for draft in fixture["drafts"]:
        packet = packets.get(int(draft["obs_id"]))
        if packet is None:
            stale.append((draft["obs_id"], "no packet"))
        elif packet.sha256() != draft["packet_sha256"]:
            stale.append((draft["obs_id"], "packet changed"))
    assert not stale, (
        f"{stale}. The publisher retires these rather than judging them, so the receipt "
        f"stays honest, but a re-freeze is what actually fixes it."
    )


