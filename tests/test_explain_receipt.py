"""The published note receipt has to agree with the frozen drafts and with the console.

Three things can drift apart here and each one is invisible from the others. The frozen
drafts can stop matching the packets they were written from, because the console data is
regenerated by a different script. The receipt can stop matching the drafts, because it is
produced by a run that could have happened at any time. And the console's ``notes.json``
can stop matching the receipt, because it is a second file written in the same pass. So all
three are compared here rather than trusted.

Every check recomputes rather than reads. A receipt that asserts a refusal rate is only
evidence if the rate can be re-derived from the rows beside it, and the rows are only
evidence if the drafts they judge are the drafts the console shipped.
"""

from __future__ import annotations

import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

import pytest

from pipeline.tracetriage.explain import (
    adversarial_drafts,
    build_packet,
    control_drafts,
    prompt_contract_sha256,
    verify_note,
)

REPO = Path(__file__).resolve().parents[1]
_DATA = REPO / "apps" / "web" / "public" / "data"
_RECEIPT = REPO / "artifacts" / "EXPLAIN_RECEIPT.json"
_NOTES = _DATA / "notes.json"
_FIXTURE = REPO / "tests" / "fixtures" / "granite_notes.json"


def _load(path: Path) -> dict:
    if not path.exists():
        pytest.skip(f"{path.relative_to(REPO)} has not been generated")
    return json.loads(path.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def receipt() -> dict:
    return _load(_RECEIPT)


@pytest.fixture(scope="module")
def fixture() -> dict:
    return _load(_FIXTURE)


@pytest.fixture(scope="module")
def notes() -> dict:
    return _load(_NOTES)


@pytest.fixture(scope="module")
def packets():
    cards = json.loads((_DATA / "cards.json").read_text(encoding="utf-8"))["cards"]
    entries = json.loads((_DATA / "queue.json").read_text(encoding="utf-8"))["entries"]
    by_id = {int(e["obs_id"]): e for e in entries}
    return {
        int(c["obs_id"]): build_packet(c, by_id[int(c["obs_id"])])
        for c in cards
        if int(c["obs_id"]) in by_id
    }


