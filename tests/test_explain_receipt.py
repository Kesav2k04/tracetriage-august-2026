def test_the_console_ships_the_note_the_receipt_describes(receipt, notes, fixture):
    by_id = {int(n["obs_id"]): n for n in notes["notes"]}
    frozen = {int(d["obs_id"]): d for d in fixture["drafts"]}
    for row in receipt["per_observation"]:
        obs_id = int(row["obs_id"])
        note = by_id[obs_id]
        assert note["source"] == row["shipped"], f"observation {obs_id}"
        if row["verdict"] == "EMITTED":
            assert note["note"] == frozen[obs_id]["draft"], f"observation {obs_id}"
            assert note["refused_codes"] == []
            assert note["why"] is None
        else:
            assert note["why"], f"observation {obs_id} ships a template with no reason"
        if row["verdict"] == "REFUSED":
            assert note["refused_codes"] == row["codes"], f"observation {obs_id}"


def test_the_console_names_the_model_that_wrote_the_notes(notes, fixture):
    assert notes["model"] == fixture["model"]
    assert notes["prompt_version"] == fixture["generation"]["prompt_version"]


