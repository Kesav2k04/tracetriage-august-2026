def _smallest_perfect_n(threshold: float) -> int:
    """The first n whose perfect rate clears the bar, from the closed form at k = n.

    The exact one-sided Clopper-Pearson lower bound at k = n is ``alpha ** (1/n)``, so
    the smallest clearing n is ``ceil(log(alpha) / log(threshold))``. Published because
    "the gate is short of observations" is a claim and this is the number behind it.
    """
    return math.ceil(math.log(0.05) / math.log(threshold))


