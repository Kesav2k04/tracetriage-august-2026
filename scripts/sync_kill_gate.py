def _gate3_verdict(g3: dict[str, Any]) -> str:
    """The verdict paragraph, derived from the receipt's own counts.

    Four branches, because "neither rate establishes the threshold" is only the right
    sentence while neither does. The version this replaced said exactly that under a
    heading that could not have said anything else.
    """
    verdict = g3["verdict"]
    threshold = g3["threshold"]
    bar = f"{threshold * 100:.0f}%"
    scored = g3["observations_scored"]
    rate = g3["discriminating_rate"]
    hits = round(rate * scored)
    bound = g3["rate_lower_bound_95"]

    grouping = g3["entity_grouping"]
    groups = grouping["groups_scored"]
    grouped_rate = grouping["grouped_discriminating_rate"] or 0.0
    grouped_hits = round(grouped_rate * groups)
    grouped_bound = grouping["grouped_rate_lower_bound_95"]
    grouped_clears = grouping["grouped_clears_threshold"]

    counts = (
        f"{hits} of {scored} testable observations discriminate ({rate * 100:.0f}%) "
        f"and {grouped_hits} of {groups} independent (station, date) "
        f"{'group does' if groups == 1 else 'groups do'}"
    )
    bounds = (
        f"The exact one-sided Clopper-Pearson 95% lower bound is `{bound:.4f}` over "
        f"observations and `{grouped_bound:.4f}` over groups"
    )

    if g3["clears_threshold"] and grouped_clears:
        return (
            f"**Gate 3 is {verdict}.** {counts}. {bounds}, and both clear the {bar} "
            f"threshold, which is what the gate asked for: the verdict follows the "
            f"interval and not the point estimate."
        )
    if g3["clears_threshold"]:
        return (
            f"**Gate 3 is {verdict}.** {counts}. {bounds}. The observation-level bound "
            f"clears the {bar} threshold and the grouped one does not, so the gate is "
            f"recorded as clearing on the weaker grouping only. The plan's rule is to "
            f"group, so this is reported rather than claimed as a pass."
        )
    if rate >= threshold:
        need = _smallest_perfect_n(threshold)
        shortfall = (
            f" A perfect rate would need {need} of {need} to clear {threshold:.2f}."
            if hits == scored
            else ""
        )
        return (
            f"**Gate 3 is {verdict}.** {counts}, and neither rate establishes the {bar} "
            f"threshold. {bounds}, so the data are consistent with a true intersection "
            f"rate well below the bar.{shortfall} The sample is what fails here, not the "
            f"measurements: the per-observation evidence is below and is unchanged by "
            f"this."
        )
    return (
        f"**Gate 3 is {verdict}.** {counts}, and the rate itself is below the {bar} "
        f"threshold before any interval is taken. {bounds}. This is not a sample-size "
        f"result: the corridor did not land on the trace often enough, on a pool fixed "
        f"in `docs/E16_PREREGISTRATION.md` before the run."
    )


def _gate3_estimands(g3: dict[str, Any]) -> str:
    """The two estimands side by side, with the pre-registered one named as the verdict.

    Every figure here is read off `artifacts/GATE3_RECEIPT.json`. The section exists
    because gate 3's threshold sentence supports two different statistics and the
    repository was publishing one of them while its note described the other. The order is
    deliberate: the statistic that decides the gate comes first in the table and in the
    prose, and the one that clears the bar is second, because it was written after the
    first had failed.
    """
    grouping = g3["entity_grouping"]
    cc = g3.get("cluster_corrected_estimand") or {}
    if not cc.get("measurable"):
        reason = cc.get("reason", "no cluster-corrected estimand is in the receipt")
        return (
            f"### Two estimands\n\n"
            f"Only the pre-registered statistic is measurable on this run: {reason} So "
            f"the grouped rate below is the only rate reported, and the verdict is read "
            f"from it."
        )

    threshold = g3["threshold"]
    bar = f"{threshold:.2f}"
    boot = cc["cluster_bootstrap"]
    lower = boot["lower_bound_95_one_sided"]
    two_lo, two_hi = boot["ci95_two_sided"]
    icc = cc["clustering"]
    sim = grouping["all_or_nothing_under_independence"]
    n_groups = grouping["groups_scored"]
    n_obs = g3["observations_scored"]
    grouped_rate = grouping["grouped_discriminating_rate"]
    grouped_bound = grouping["grouped_rate_lower_bound_95"]

    rows = [
        "| | pre-registered, decides the gate | cluster-corrected, decides nothing |",
        "|---|---|---|",
        "| Question | does the corridor discriminate on **every** scored capture at a "
        "station on a date | how often does the corridor discriminate, with the "
        "dependence between captures paid for rather than collapsed |",
        f"| Statistic | all-or-nothing indicator over {n_groups} (station, UTC date) "
        f"groups | rate over {n_obs} scored observations, cluster bootstrap over the "
        f"same {n_groups} groups |",
        f"| Value | {grouped_rate:.4f} | {cc['rate']:.4f} |",
        f"| One-sided 95% lower bound | {grouped_bound:.4f} | {lower:.4f} |",
        f"| Clears {bar} | no | yes, by {lower - threshold:.4f} |",
    ]

    verdict_para = (
        f"**The verdict stays {g3['verdict']} and the status board above still counts "
        f"this gate as unmet.** The cluster-corrected analysis in the right-hand column "
        f"was written on 2026-08-23, after the pre-registered statistic had been seen to "
        f"return {grouped_bound:.4f} against the {bar} bar. A rule adopted after seeing "
        f"the result it is applied to is not the rule that was tested. That is the whole "
        f"reason the pre-registered verdict is the one that stands here, and not the one "
        f"that clears."
    )

    margin_para = (
        f"**The margin is narrow.** {lower:.4f} against {bar}, so {lower - threshold:.4f} "
        f"of room on a bound that four bootstrap seeds place between "
        f"{boot['lower_bound_95_one_sided_range'][0]:.4f} and "
        f"{boot['lower_bound_95_one_sided_range'][1]:.4f}, with the lowest of the four "
        f"published. Read at two sides instead of one the interval is "
        f"[{two_lo:.4f}, {two_hi:.4f}], whose lower end does **not** clear {bar}. Two "
        f"other routes to the same bound agree with the bootstrap and are in the receipt: "
        f"a design-effect normal approximation gives "
        f"{cc['design_effect_normal_lower_bound_95']:.4f} and an exact binomial bound at "
        f"an effective n of {cc['effective_n_exact_lower_bound_95']['n_effective']:.1f} "
        f"gives {cc['effective_n_exact_lower_bound_95']['lower_bound']:.4f}. Nothing here "
        f"is a comfortable pass."
    )

    clustering_para = (
        f"**The clustering the grouping exists to answer is real.** One-way ICC "
        f"{icc['icc']:.4f} on the discriminating indicator over "
        f"{icc['n_groups']} station-days holding {icc['mean_group_size']:.2f} "
        f"observations each, so a design effect of {icc['design_effect']:.4f}. The rate "
        f"still clears the bar after paying for it. This is the same one-way ICC gate 6 "
        f"uses, from `queue.intraclass_correlation`, so the two gates cannot disagree "
        f"about what clustering means."
    )

    collapse_para = (
        f"**What the pre-registered statistic is measuring, measured.** An all-or-nothing "
        f"indicator over groups of mean size {sim['mean_group_size']:.2f} and maximum "
        f"{sim['max_group_size']} falls as groups grow whether or not any dependence "
        f"exists, so its value is not evidence about dependence. Holding the "
        f"per-observation rate at its observed {sim['per_observation_rate_held_at']:.4f} "
        f"and drawing every outcome independently, so with zero clustering, the all-pass "
        f"group rate over these same sizes comes out at "
        f"{sim['mean_all_pass_group_rate']:.4f} with a 95% range of "
        f"{sim['range95'][0]:.4f} to {sim['range95'][1]:.4f} over "
        f"{sim['n_draws']:,} draws. The published {grouped_rate:.4f} sits inside that "
        f"range. And the bar is out of reach of this statistic rather than merely "
        f"unmet: {sim['draws_reaching_the_threshold']} of {sim['n_draws']:,} draws "
        f"reached {bar}, the largest reaching "
        f"{sim['max_all_pass_group_rate_drawn']:.4f}, and in expectation the collapsed "
        f"statistic needs a per-observation rate near "
        f"{sim['per_observation_rate_needed_to_reach_the_threshold']:.4f} before it can "
        f"touch {bar} at these group sizes. So the collapse is a stricter question rather "
        f"than a corrected version of the gate's own one, and its value is set mostly by "
        f"the group-size distribution."
    )

    closing = (
        "Both are in `artifacts/GATE3_RECEIPT.json`: the pre-registered one under "
        "`entity_grouping`, the second under `cluster_corrected_estimand`, which carries "
        "`decides_the_gate: false` so a consumer cannot read it as the verdict."
    )

    return "\n\n".join([
        "### Two estimands, and why the pre-registered one is the verdict",
        (
            "Gate 3's threshold is worded as a rate over reviewed positive examples. Two "
            "different statistics can be built from that sentence, and both are reported "
            "here because they answer different questions."
        ),
        "\n".join(rows),
        verdict_para,
        margin_para,
        clustering_para,
        collapse_para,
        closing,
    ])


def _load_optional(name: str) -> dict[str, Any] | None:
    """A receipt that may not exist yet, without turning its absence into a crash.

    The pool A comparison run is a separate invocation of `scripts/run_gate3.py`, so
    there is a window where the gate has an answer and the comparison does not. That
    window renders as "not run" rather than as a missing row.
    """
    path = REPO / "artifacts" / name
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def _status_phrase(status: str) -> str:
    """A pool status as something a reader can read, without hiding an unknown one.

    An unrecognised status is printed rather than mapped to a friendly default, because
    a new refusal reason silently rendering as an old one is how a count stops meaning
    what the sentence around it says.
    """
    known = {
        "no_waterfall": "had no waterfall image",
        "swing_below_floor": "have a predicted Doppler swing too small to tell the two "
        "shapes apart",
        "no_measurable_rows": "had no image row with the spread to carry a z-score",
    }
    if status in known:
        return known[status]
    if status.startswith("physics_"):
        return f"failed physics ({status[len('physics_'):]})"
    if status.startswith("geometry_"):
        return f"failed geometry ({status[len('geometry_'):]})"
    if status.startswith("worker_failed"):
        return "crashed while being examined"
    return f"carry status `{status}`"


def _pool_row(label: str, r: dict[str, Any] | None, note: str) -> str:
    """One pool's five numbers, or an honest blank when that run has not happened."""
    if r is None:
        return f"| {label} | not run | | | | | {note} |"
    n = r["observations_scored"]
    rate = r["discriminating_rate"]
    hits = round(rate * n) if n else 0
    bound = r["rate_lower_bound_95"]
    return (
        f"| {label} | {n} | {hits} | {rate * 100:.0f}% | "
        f"{bound:.4f} | {r['verdict']} | {note} |"
    )


def _gate3_pools(g3: dict[str, Any], g3a: dict[str, Any] | None) -> str:
    """The two pools side by side, and what their difference means.

    Pool A is A3's own `UNCORRECTED` label, which is `sigma_curved - sigma_vertical >= 3`.
    Selecting on that and then testing whether the corridor discriminates measures the
    selection, so pool A cannot decide the gate and is here only as the comparison that
    shows how large that effect is.
    """
    threshold = g3["threshold"]
    # Which pool produced the published receipt is read off the receipt, never assumed.
    # This label was hardcoded to pool B, and against the A3 run actually in the tree it
    # announced a corridor-free pre-registered pool for observations the corridor chose,
    # which is the one substitution E16 exists to prevent.
    name = (g3.get("pool") or {}).get("name", "a3")
    labels = {
        "pool_b": ("**B, pre-registered**", "a corridor-free presence statistic"),
        "pool_a": ("A, corridor-selected", "A3's `UNCORRECTED` label, which reads the corridor"),
        "a3": ("A3's decisive set", "A3's verdict word, before E16 split the pools"),
    }
    main_label, main_note = labels.get(name, (f"`{name}`", "an unrecognised selector"))
    rows = [
        "| pool | scored | discriminating | rate | 95% lower bound | verdict | selected by |",
        "|---|---|---|---|---|---|---|",
        _pool_row(main_label, g3, main_note),
    ]
    if name != "pool_a":
        rows.append(
            _pool_row(
                "A, corridor-selected", g3a,
                "A3's `UNCORRECTED` label, which reads the corridor",
            )
        )
    if name == "a3":
        return "\n".join(rows) + "\n\n" + (
            "The published receipt is still A3's decisive set, chosen before "
            "`docs/E16_PREREGISTRATION.md` split the pools. Neither pre-registered pool "
            "has been scored yet, so there is no comparison to draw and this table says "
            "so rather than presenting one pool's rate as both."
        )
    tail = (
        f"Only pool B decides the gate, at a threshold of {threshold:.2f}. Pool A is "
        "selected on `sigma_curved - sigma_vertical >= 3`, so asking whether the corridor "
        "discriminates on it is asking whether the thing it was selected for is true of "
        "it. The two rates are published together because the gap between them is the "
        "size of that circularity, and a reader cannot judge it from one number."
    )
    if g3a is not None:
        gap = (g3a["discriminating_rate"] - g3["discriminating_rate"]) * 100
        tail += (
            f" Measured here it is {gap:+.0f} percentage points."
        )

    # The denominator, and where it went. A pool rate published without the population it
    # was drawn from lets 100% of a small tail read as 100% of the snapshot.
    counts = (g3.get("pool") or {}).get("pool_counts") or {}
    if counts.get("examined"):
        by_status = counts.get("by_status") or {}
        dropped = sorted(
            ((k, v) for k, v in by_status.items() if k != "ok"),
            key=lambda kv: -kv[1],
        )
        reasons = ", ".join(f"{v:,} {_status_phrase(k)}" for k, v in dropped)
        tail += (
            f"\n\nThe pools are drawn from {counts['examined']:,} observations, the whole "
            f"snapshot. {counts.get('measurable', 0):,} were measured"
            + (f" and the rest were dropped: {reasons}." if reasons else ".")
            + f" Pool B took {counts.get('pool_b', 0):,} of them and pool A "
            f"{counts.get('pool_a', 0):,}, sharing {counts.get('in_both', 0):,}. Every "
            f"observation's own `trace_q75` is in `artifacts/GATE3_POOL.json` whether it "
            f"was selected or not, so the pool can be recut at another bar from that file."
        )
    return "\n".join(rows) + "\n\n" + tail


def _gate3_entry(g3: dict) -> str:
    """The failure-log entry, following the receipt rather than asserting around it.

    Every number here was already read from the receipt. The sentences holding them were
    not, and they were written when the pool was three observations: this rendered
    "discriminates on every testable observation: 224 of 289", "a rate of 0.8", and a
    lower bound of 0.7309 described as "roughly half" a threshold of 0.70, which it
    clears. Numbers that are generated inside prose that is not degrade into confident
    nonsense the moment the measurement moves, and they degrade in the direction of the
    last thing that was true.
    """
    n_scored = g3["observations_scored"]
    n_hits = _n_discriminating(g3)
    grouped = g3["entity_grouping"]
    nulls = _n_nulls(g3)
    bar = g3["threshold"] * 100
    bound = g3["rate_lower_bound_95"]
    grouped_bound = grouped.get("grouped_rate_lower_bound_95")
    groups = grouped.get("groups_scored")

    coverage = (
        "every testable observation"
        if n_hits == n_scored
        else f"{n_hits / n_scored * 100:.1f}% of them"
    )

    if g3["clears_threshold"] and grouped.get("grouped_clears_threshold"):
        outcome = (
            f"That bound clears the {bar:.0f}% bar, and so does the bound over the "
            f"{groups} independent {grouped['group_key']} episodes, "
            f"{grouped_bound:.4f}."
        )
    elif g3["clears_threshold"]:
        outcome = (
            f"That bound clears the {bar:.0f}% bar. Over the {groups} independent "
            f"{grouped['group_key']} episodes those observations span it is "
            f"{grouped_bound:.4f} and does not, and the plan groups before it decides, "
            "because a ground station's oscillator error is common to every pass it "
            "records. So the observation-level pass is reported and not claimed."
        )
    elif g3["discriminating_rate"] >= g3["threshold"]:
        smallest = _smallest_perfect_n(g3["threshold"])
        outcome = (
            f"The rate is above the {bar:.0f}% bar and the bound is not, so the rate is "
            f"not established at this sample size. At a perfect rate the smallest "
            f"sample whose bound clears it is {smallest} of {smallest}."
        )
    else:
        outcome = (
            f"Both the rate and its bound are under the {bar:.0f}% bar, so this is a "
            "measured shortfall rather than a question of sample size."
        )

    return (
        f"{GATE3_OPENER} `clears_threshold` compared the point estimate against the "
        "bar, and 1.0 \u2265 0.70 is True for 1 of 1 as much as for 3 of 3. The gate "
        f"reads {g3['verdict']} as of the receipt in this tree, which is the state "
        "described from here on rather than the state on the date above. "
        f"The expected corridor discriminates on {coverage}: "
        f"{n_hits} of {n_scored}, each beating {nulls} corridors built by permuting its "
        f"own Doppler samples in time with none reaching it "
        f"(p = {1 / (nulls + 1):.3f}), and each beating all four scaled-swing controls "
        "that hold shape and smoothness fixed and vary only magnitude. The gate asks "
        f"for a rate of {bar:.0f}%; the measured rate is "
        f"{g3['discriminating_rate'] * 100:.1f}% on {n_scored} trials, whose exact "
        f"one-sided 95% Clopper-Pearson lower bound is {bound:.4f}. {outcome} "
        f"{GATE3_CLOSER}"
    )


