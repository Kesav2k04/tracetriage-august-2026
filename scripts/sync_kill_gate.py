def _gate3_verdict(g3: dict[str, Any]) -> str:
    """The verdict paragraph, derived from the receipt's own counts.

    Four branches, because "neither rate establishes the threshold" is only the right
    sentence while neither does. The version this replaced said exactly that under a
    heading that could not have said anything else.
    """
    verdict = g3["verdict"]
    threshold = g3["threshold"]
    bar = f"{threshold * 100:.0f}%"
    scored = g3["observations_scored"]
    rate = g3["discriminating_rate"]
    hits = round(rate * scored)
    bound = g3["rate_lower_bound_95"]

    grouping = g3["entity_grouping"]
    groups = grouping["groups_scored"]
    grouped_rate = grouping["grouped_discriminating_rate"] or 0.0
    grouped_hits = round(grouped_rate * groups)
    grouped_bound = grouping["grouped_rate_lower_bound_95"]
    grouped_clears = grouping["grouped_clears_threshold"]

    counts = (
        f"{hits} of {scored} testable observations discriminate ({rate * 100:.0f}%) "
        f"and {grouped_hits} of {groups} independent (station, date) "
        f"{'group does' if groups == 1 else 'groups do'}"
    )
    bounds = (
        f"The exact one-sided Clopper-Pearson 95% lower bound is `{bound:.4f}` over "
        f"observations and `{grouped_bound:.4f}` over groups"
    )

    if g3["clears_threshold"] and grouped_clears:
        return (
            f"**Gate 3 is {verdict}.** {counts}. {bounds}, and both clear the {bar} "
            f"threshold, which is what the gate asked for: the verdict follows the "
            f"interval and not the point estimate."
        )
    if g3["clears_threshold"]:
        return (
            f"**Gate 3 is {verdict}.** {counts}. {bounds}. The observation-level bound "
            f"clears the {bar} threshold and the grouped one does not, so the gate is "
            f"recorded as clearing on the weaker grouping only. The plan's rule is to "
            f"group, so this is reported rather than claimed as a pass."
        )
    if rate >= threshold:
        need = _smallest_perfect_n(threshold)
        shortfall = (
            f" A perfect rate would need {need} of {need} to clear {threshold:.2f}."
            if hits == scored
            else ""
        )
        return (
            f"**Gate 3 is {verdict}.** {counts}, and neither rate establishes the {bar} "
            f"threshold. {bounds}, so the data are consistent with a true intersection "
            f"rate well below the bar.{shortfall} The sample is what fails here, not the "
            f"measurements: the per-observation evidence is below and is unchanged by "
            f"this."
        )
    return (
        f"**Gate 3 is {verdict}.** {counts}, and the rate itself is below the {bar} "
        f"threshold before any interval is taken. {bounds}. This is not a sample-size "
        f"result: the corridor did not land on the trace often enough, on a pool fixed "
        f"in `docs/E16_PREREGISTRATION.md` before the run."
    )


def _load_optional(name: str) -> dict[str, Any] | None:
    """A receipt that may not exist yet, without turning its absence into a crash.

    The pool A comparison run is a separate invocation of `scripts/run_gate3.py`, so
    there is a window where the gate has an answer and the comparison does not. That
    window renders as "not run" rather than as a missing row.
    """
    path = REPO / "artifacts" / name
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def _pool_row(label: str, r: dict[str, Any] | None, note: str) -> str:
    """One pool's five numbers, or an honest blank when that run has not happened."""
    if r is None:
        return f"| {label} | not run | | | | | {note} |"
    n = r["observations_scored"]
    rate = r["discriminating_rate"]
    hits = round(rate * n) if n else 0
    bound = r["rate_lower_bound_95"]
    return (
        f"| {label} | {n} | {hits} | {rate * 100:.0f}% | "
        f"{bound:.4f} | {r['verdict']} | {note} |"
    )


def _gate3_pools(g3: dict[str, Any], g3a: dict[str, Any] | None) -> str:
    """The two pools side by side, and what their difference means.

    Pool A is A3's own `UNCORRECTED` label, which is `sigma_curved - sigma_vertical >= 3`.
    Selecting on that and then testing whether the corridor discriminates measures the
    selection, so pool A cannot decide the gate and is here only as the comparison that
    shows how large that effect is.
    """
    threshold = g3["threshold"]
    # Which pool produced the published receipt is read off the receipt, never assumed.
    # This label was hardcoded to pool B, and against the A3 run actually in the tree it
    # announced a corridor-free pre-registered pool for observations the corridor chose,
    # which is the one substitution E16 exists to prevent.
    name = (g3.get("pool") or {}).get("name", "a3")
    labels = {
        "pool_b": ("**B, pre-registered**", "a corridor-free presence statistic"),
        "pool_a": ("A, corridor-selected", "A3's `UNCORRECTED` label, which reads the corridor"),
        "a3": ("A3's decisive set", "A3's verdict word, before E16 split the pools"),
    }
    main_label, main_note = labels.get(name, (f"`{name}`", "an unrecognised selector"))
    rows = [
        "| pool | scored | discriminating | rate | 95% lower bound | verdict | selected by |",
        "|---|---|---|---|---|---|---|",
        _pool_row(main_label, g3, main_note),
    ]
    if name != "pool_a":
        rows.append(
            _pool_row(
                "A, corridor-selected", g3a,
                "A3's `UNCORRECTED` label, which reads the corridor",
            )
        )
    if name == "a3":
        return "\n".join(rows) + "\n\n" + (
            "The published receipt is still A3's decisive set, chosen before "
            "`docs/E16_PREREGISTRATION.md` split the pools. Neither pre-registered pool "
            "has been scored yet, so there is no comparison to draw and this table says "
            "so rather than presenting one pool's rate as both."
        )
    tail = (
        f"Only pool B decides the gate, at a threshold of {threshold:.2f}. Pool A is "
        "selected on `sigma_curved - sigma_vertical >= 3`, so asking whether the corridor "
        "discriminates on it is asking whether the thing it was selected for is true of "
        "it. The two rates are published together because the gap between them is the "
        "size of that circularity, and a reader cannot judge it from one number."
    )
    if g3a is not None:
        gap = (g3a["discriminating_rate"] - g3["discriminating_rate"]) * 100
        tail += (
            f" Measured here it is {gap:+.0f} percentage points, on pools sharing "
            f"{g3.get('pool', {}).get('n_in_both', 'some')} observations."
        )
    return "\n".join(rows) + "\n\n" + tail


