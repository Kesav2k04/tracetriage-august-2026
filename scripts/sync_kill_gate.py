def _n_discriminating(g3: dict) -> int:
    return sum(
        1 for o in g3["observations"] if o["null_calibration"]["discriminates"]
    )


def _n_nulls(g3: dict) -> int:
    """The null count the scored observations actually ran.

    Not-testable observations carry `n_nulls: 0` because they were never scored, so
    reading the first observation's value would publish 0 nulls for a gate that ran
    200. Take it from a scored one, and refuse to guess if they disagree.
    """
    counts = {
        o["null_calibration"]["n_nulls"]
        for o in g3["observations"]
        if o["null_calibration"]["p_value"] is not None
    }
    if len(counts) != 1:
        raise ValueError(f"scored observations disagree on n_nulls: {sorted(counts)}")
    return counts.pop()


def _gate3_row(g3: dict) -> str:
    """One table cell, and the clause in it that used to assert its own conclusion.

    This rendered ", so a 70% rate is not established" whatever the numbers said. On
    E16's pool the exact lower bound is 0.731, which clears 0.70, so the summary table at
    the top of this document printed a bound that clears the bar and a sentence denying
    it, in the same cell. The clause follows the bound now.
    """
    grouping = g3["entity_grouping"]
    bar = g3["threshold"] * 100
    bound = g3["rate_lower_bound_95"]
    grouped_bound = grouping.get("grouped_rate_lower_bound_95")
    groups = grouping.get("groups_scored")

    if g3["clears_threshold"] and grouping.get("grouped_clears_threshold"):
        clause = (
            f"which clears the {bar:.0f}% bar over observations and over the "
            f"{groups} independent episodes"
        )
    elif g3["clears_threshold"]:
        clause = (
            f"which clears the {bar:.0f}% bar. Over {groups} independent "
            f"(station, date) episodes the bound is "
            f"{grouped_bound:.3f} and does not, and the plan groups before it decides"
        )
    elif g3["discriminating_rate"] >= g3["threshold"]:
        clause = f"so a {bar:.0f}% rate is not established at this sample size"
    else:
        clause = f"and the rate itself is under the {bar:.0f}% bar"

    days = grouping["distinct_days"]
    stations = grouping["distinct_stations"]
    return (
        f"| 3 | {TITLES[3]} | {THRESHOLDS[3]} "
        f"| **{g3['verdict']}. {_n_discriminating(g3)}/"
        f"{g3['observations_scored']} testable discriminate "
        f"({g3['discriminating_rate'] * 100:.0f}%), the exact one-sided 95% lower "
        f"bound on that rate is {bound:.3f}, {clause}. "
        f"{g3['observations_not_testable']} of {g3['observations_decisive']} not "
        f"testable; the {g3['observations_scored']} span "
        f"{stations} {'station' if stations == 1 else 'stations'} on "
        f"{days} {'night' if days == 1 else 'nights'}** |"
    )


def _narrow_arm_clause(brier: dict | None, aurc: dict | None) -> str:
    """What the narrower arm has established, read from its two corrected verdicts.

    This clause said "does clear zero and survives correction" as a literal until
    2026-08-19, when correcting over the 21 comparisons the ablation rule reads rather
    than the 7 on one split moved the Brier interval across zero while the risk-coverage
    interval stayed clear of it. A sentence that cannot express that outcome would have
    kept reporting the old one from a receipt that no longer said it.
    """
    def survives(comp: dict | None) -> bool | None:
        if not comp:
            return None
        return bool(comp.get("survives_correction")) and (
            comp.get("direction_adjusted", comp.get("direction")) == "challenger_better"
        )

    b, a = survives(brier), survives(aurc)
    family = (brier or aurc or {}).get("n_comparisons")
    over = f" over the {family} comparisons the ablation rule reads" if family else ""
    if b is None or a is None:
        return (
            "A narrower arm (image + corridor) leads on both metrics; its corrected "
            "intervals are in the receipt"
        )
    if b and a:
        return (
            "A narrower arm (image + corridor) clears zero on both Brier and "
            f"risk-coverage area and survives correction{over}"
        )
    if a and not b:
        return (
            "A narrower arm (image + corridor) leads on both metrics: its risk-coverage "
            f"margin survives correction{over} and its Brier margin does not"
        )
    if b and not a:
        return (
            "A narrower arm (image + corridor) leads on both metrics: its Brier margin "
            f"survives correction{over} and its risk-coverage margin does not"
        )
    return (
        "A narrower arm (image + corridor) leads on both metrics and neither margin "
        f"survives correction{over}"
    )


