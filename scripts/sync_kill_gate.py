def _ci(pair: list[float] | None) -> str:
    """One interval, at the three decimals the rest of this document uses."""
    if not pair or any(v is None or v != v for v in pair):
        return "not measurable"
    return f"[{pair[0]:.3f}, {pair[1]:.3f}]"


def _per_split_table(queue: dict) -> str:
    """Gate 6's four splits, read from the receipt rather than remembered."""
    decisive = {s["split"]: s["n_test_decisive"] for s in queue["per_split_summaries"]}
    rows = [
        "| Split | Verdict | Point lift | Episode CI | Station CI "
        "| Governing (union) | n_decisive |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, split in queue["gate6"]["per_split"].items():
        if not split.get("measurable"):
            reason = split.get("not_measurable_reason") or "no reason recorded"
            rows.append(
                f"| {name} | NOT_MEASURABLE | | | | | {decisive.get(name, '')} |"
                f" <!-- {reason} -->"
            )
            continue
        rows.append(
            f"| {name} | {split['verdict']} | {split['lift_point']:.3f} "
            f"| {_ci(split.get('lift_ci95_episode'))} "
            f"| {_ci(split.get('lift_ci95_station'))} "
            f"| {_ci(split.get('lift_ci95'))} "
            f"| {decisive.get(name, '')} |"
        )
    return "\n".join(rows)


def _gate4_arm(receipt: dict) -> str:
    """The paragraph for a review that happened and does not answer the gate.

    Generated rather than written because it carries seven numbers. A hand-written version
    of this is the exact drift this file exists to prevent, and it would drift in the
    direction that flatters the project: an arm's rate reads like the gate's rate unless
    something keeps the two apart on every re-run.
    """
    arm = receipt.get("arm")
    if not arm:
        if (receipt.get("reviewer") or {}).get("kind") == "human":
            return _gate4_human(receipt)
        return (
            "No review has been recorded. The receipt carries "
            f"`{receipt.get('verdict')}` and no rate."
        )
    reviewer = arm["reviewer"]
    intra = arm["intra_rater"]
    axes = arm["network_label_agreement"]["by_axis"]
    seen, shape = axes["visible_signal"], axes["target_consistent"]
    return (
        f"**A review has been carried out and it does not answer this gate.** "
        f"{arm['decisive']} of {arm['observations_scored']} first-occurrence observations "
        f"were decidable, a rate of {arm['rate']:.4f}, exact one-sided 95% "
        f"[{arm['rate_lower_bound_95']:.4f}, {arm['rate_upper_bound_95']:.4f}] against the "
        f"0.80 threshold, with {intra['identical_on_all_three_axes']} of "
        f"{intra['repeated_pairs_scored']} repeated pairs answered identically on all three "
        f"axes. Agreement with the network's own label is "
        f"{seen['agreed_with_the_network_label']} of {seen['items_scored']} on the "
        f"visible-signal axis and {shape['agreed_with_the_network_label']} of "
        f"{shape['items_scored']} on the target-consistency axis, and neither of those is "
        f"the network's question: one counts a fixed local carrier as a signal, the other "
        f"wants a drifting curve and a packet burst near zero offset answers no to it. They "
        f"miss it in opposite directions, so both are published with their confusion "
        f"matrices and neither is named the right one. The reviewer was "
        f"**{reviewer['kind']}**, not a person: {reviewer['identity']} So the gate's own "
        f"verdict stays `{receipt['verdict']}` and this table still reads OPEN. What the arm "
        f"establishes is narrower than the gate and worth having on its own: the committed "
        f"sample supports a decisive judgment on the published instrument with every label "
        f"hidden, which was never measured before. What it cannot establish is whether a "
        f"person can do it, because the instrument the gate names is a person and this was "
        f"not one."
    )


def _gate4_human(receipt: dict) -> str:
    """The paragraph for the review the gate actually asks for.

    Generated for the same reason the arm paragraph is: it carries eight numbers, and a
    hand-written version would drift towards the flattering reading. It also has to say
    what the earlier model review becomes once a person has answered, because the two
    numbers invite being read as one and they are not: one is the gate, the other is a
    measurement of the sample that the gate does not ask for.
    """
    reviewer = receipt["reviewer"]
    intra = receipt["intra_rater"]
    axes = receipt["network_label_agreement"]["by_axis"]
    seen, shape = axes["visible_signal"], axes["target_consistent"]
    verdict = receipt["verdict"]
    settled = {
        "PASSED": "clears the 0.80 threshold, so the gate is met",
        "FAILED": (
            "sits below the 0.80 threshold, so the gate is not met and the finding is "
            "about the labelling protocol rather than about the model"
        ),
        "NOT_ESTABLISHED": (
            "contains the 0.80 threshold, so the gate is not met: a point estimate above "
            "the bar whose interval straddles it is published here as a failure, exactly "
            "as it is for gates 3, 5 and 6"
        ),
    }.get(verdict, "is reported as it came back")
    # A high decisive rate beside a low intra-rater rate is the one reading of this gate a
    # sceptical reader arrives at unaided, so it is stated here rather than left for them to
    # find. The two numbers answer different questions and the gap between them is a real
    # limit on what the gate established: that the plates can be judged, not that the
    # judgment is stable.
    intra_rate = intra["rate_identical_on_all_three_axes"]
    tension = ""
    if receipt["rate"] - intra_rate >= 0.15:
        tension = (
            f" Those two numbers should be read together and they are not the same claim. "
            f"Every plate supported a judgment, and on "
            f"{intra['repeated_pairs_scored'] - intra['identical_on_all_three_axes']} of "
            f"{intra['repeated_pairs_scored']} repeated plates the same reviewer reached a "
            f"different judgment the second time. Decidability at {receipt['rate']:.4f} is "
            f"what this gate asked for and what it establishes. Reliability at "
            f"{intra_rate:.4f} is a separate property, it is the weaker of the two, and no "
            f"claim here rests on it."
        )
    prior = receipt.get("prior_review")
    also = ""
    if prior:
        also = (
            f" A model answered the same committed sample before a person did, and that "
            f"review is kept in `prior_review` rather than deleted: "
            f"{prior['decisive']} of {prior['observations_scored']} decidable at "
            f"{prior['rate']:.4f}, by {prior['reviewer']['identity']} It is not this gate "
            f"and never was. What the two together allow, which neither allows alone, is a "
            f"comparison of a model reviewer against a person on identical blinded plates, "
            f"and it does not go the way a reader would guess: the model was less decisive "
            f"({prior['rate']:.4f} against {receipt['rate']:.4f}) and more self-consistent "
            f"({prior['intra_rater']['identical_on_all_three_axes']} of "
            f"{prior['intra_rater']['repeated_pairs_scored']} repeated pairs against "
            f"{intra['identical_on_all_three_axes']} of "
            f"{intra['repeated_pairs_scored']}). Neither arm is the other's control and "
            f"this is one reviewer of each kind, so it is published as an observation and "
            f"not as a result."
        )
    return (
        f"**A person has answered this worksheet and the gate is decided.** "
        f"{receipt['decisive']} of {receipt['observations_scored']} first-occurrence "
        f"observations were decidable, a rate of {receipt['rate']:.4f}, exact one-sided 95% "
        f"[{receipt['rate_lower_bound_95']:.4f}, {receipt['rate_upper_bound_95']:.4f}], "
        f"which {settled}. Intra-rater agreement is "
        f"{intra['identical_on_all_three_axes']} of {intra['repeated_pairs_scored']} "
        f"repeated pairs answered identically on all three axes, which bounds how far the "
        f"first number can be trusted. Agreement with the network's own label is "
        f"{seen['agreed_with_the_network_label']} of {seen['items_scored']} on the "
        f"visible-signal axis and {shape['agreed_with_the_network_label']} of "
        f"{shape['items_scored']} on the target-consistency axis, and neither of those is "
        f"the network's question.{tension} The reviewer was **{reviewer['kind']}**: "
        f"{reviewer['identity']} {reviewer['independence']}{also}"
    )


def _replace_between(text: str, opener: str, closer: str, new: str) -> str:
    """Swap the block that runs from `opener` to the end of `closer`, exactly once."""
    if text.count(opener) != 1:
        raise ValueError(f"expected exactly one {opener!r}, found {text.count(opener)}")
    start = text.index(opener)
    end = text.index(closer, start) + len(closer)
    return text[:start] + new + text[end:]


def render(text: str) -> str:
    """The document as the receipts say it should read. Pure, so a test can call it."""
    queue = _load("QUEUE_RECEIPT.json")
    fusion = _load("FUSION_RECEIPT.json")
    g3 = _load("GATE3_RECEIPT.json")
    g4 = _load("GATE4_RECEIPT.json")

    chron = queue["gate6"]["per_split"]["chronological"]
    station = queue["gate6"]["per_split"]["cold_station"]
    g5 = fusion["gate5"]["per_split"]["chronological"]
    # The narrower arm's two corrected verdicts, from the split the gate is taken on.
    chron_split = next(
        (s for s in fusion["splits"] if s["split"] == "chronological"), {}
    )
    narrow_brier = (chron_split.get("multiplicity_adjusted") or {}).get(
        "image_corridor_vs_image_only"
    )
    narrow_aurc = (chron_split.get("selective") or {}).get(
        "aurc_shipped_vs_image_only"
    )
    # Gate 6's decisive count and gate 5's are different populations, and the document
    # had been quoting gate 5's 88 for both. Gate 6 runs on the queue, which
    # deduplicates 410 rows to 407, and one of the removed rows was decisive.
    decisive = {s["split"]: s for s in queue["per_split_summaries"]}["chronological"][
        "n_test_decisive"
    ]

    table = "\n".join(
        [
            "| # | Gate | Threshold | Status |",
            "|---|---|---|---|",
            _STATIC_ROWS[1],
            _STATIC_ROWS[2],
            _gate3_row(g3),
            _gate4_row(),
            _gate5_row(g5, narrow_brier, narrow_aurc),
            _gate6_row(chron, station, decisive),
        ]
    )

    # The summary table is whatever sits between the heading and the next rule.
    start = text.index(STATUS_HEADING) + len(STATUS_HEADING)
    end = text.index(RULE, start)
    text = text[:start] + "\n" + table + "\n" + text[end:]

    text = _replace_between(
        text, GATE6_OPENER, GATE6_CLOSER, _gate6_entry(queue, chron, station, decisive)
    )

    if PER_SPLIT_OPEN not in text or PER_SPLIT_CLOSE not in text:
        raise SystemExit(
            f"docs/KILL_GATE.md has no {PER_SPLIT_OPEN} ... {PER_SPLIT_CLOSE} region, "
            "so the per-split table has nowhere to go. Add the two comment markers "
            "around it."
        )
    text = _replace_between(
        text,
        PER_SPLIT_OPEN,
        PER_SPLIT_CLOSE,
        f"{PER_SPLIT_OPEN}\n{_per_split_table(queue)}\n{PER_SPLIT_CLOSE}",
    )

    if GATE4_ARM_OPEN not in text or GATE4_ARM_CLOSE not in text:
        raise SystemExit(
            f"docs/KILL_GATE.md has no {GATE4_ARM_OPEN} ... {GATE4_ARM_CLOSE} region, so "
            "gate 4's arm paragraph has nowhere to go. Add the two comment markers around "
            "it. A gate whose numbers have no generated home is a gate whose numbers go "
            "stale by hand."
        )
    text = _replace_between(
        text,
        GATE4_ARM_OPEN,
        GATE4_ARM_CLOSE,
        f"{GATE4_ARM_OPEN}\n{_gate4_arm(g4)}\n{GATE4_ARM_CLOSE}",
    )

    for opener, closer, body, what in (
        (GATE3_HEAD_OPEN, GATE3_HEAD_CLOSE, _gate3_heading(g3), "gate 3's heading"),
        (GATE3_VERDICT_OPEN, GATE3_VERDICT_CLOSE, _gate3_verdict(g3), "gate 3's verdict"),
        (
            GATE3_POOLS_OPEN, GATE3_POOLS_CLOSE,
            _gate3_pools(g3, _load_optional("GATE3_POOL_A_RECEIPT.json")),
            "gate 3's pool comparison",
        ),
    ):
        if opener not in text or closer not in text:
            raise SystemExit(
                f"docs/KILL_GATE.md has no {opener} ... {closer} region, so {what} has "
                "nowhere to go. Add the two comment markers around it. A number whose "
                "only home is a typed line is a number that goes stale by hand."
            )
        text = _replace_between(text, opener, closer, f"{opener}\n{body}\n{closer}")

    gate3_entry = _gate3_entry(g3)
    if GATE3_OPENER in text:
        text = _replace_between(text, GATE3_OPENER, GATE3_CLOSER, gate3_entry)
    else:
        # A gate that changed verdict belongs in the failure log, above gate 6's entry
        # so the log stays in gate order.
        text = text.replace(GATE6_OPENER, gate3_entry + "\n\n" + GATE6_OPENER, 1)

    return text


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check",
        action="store_true",
        help="write nothing; exit 1 if the document is out of date",
    )
    args = ap.parse_args()

    before = DOC.read_text(encoding="utf-8")
    after = render(before)

    if args.check:
        if before == after:
            print("KILL_GATE.md is in sync with the receipts")
            return 0
        print("KILL_GATE.md is OUT OF SYNC with the receipts; run without --check")
        return 1

    if before == after:
        print("KILL_GATE.md already in sync; nothing written")
        return 0
    DOC.write_text(after, encoding="utf-8", newline="\n")
    print("KILL_GATE.md synced to the receipts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
